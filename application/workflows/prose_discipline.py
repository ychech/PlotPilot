"""章节正文「反八股 / 控水分」约束块，供主工作流与 DAG 等共用。

解决模型常见恶习：「不是…而是…」纠正式排比、破折号叠比喻、
「除了/除此之外/此外」补充式八股、
同一段感受换三种说法、为凑字数重复描写同一致震撼等。
"""
from __future__ import annotations

from typing import Optional


def build_prose_discipline_block(
    *,
    beat_mode: bool = False,
    beat_target_words: Optional[int] = None,
) -> str:
    """组装注入 system 的行文目标段落（中文）。"""
    lines = [
        "【行文目标：反八股 / 控水分】",
        "",
        "**最高原则**：以下规则服务于讲好故事。若逐条执行会让文字僵硬或产生新的套路感，优先保持事件清楚、人物可信、情绪自然。",
        "",
        "**纠正式对照（慎用）**：减少在同一句或紧挨两句里用「否定甲 + 肯定乙」的说教对照（含「不是…而是…」「从来不是…」「要的不是…是…」「并非…乃…」及同义变体）。想转折就拆成两句短叙，或直接写动作与结果。",
        "**补充式八股（少用）**：少用「除了……」「除此之外」「此外」「更重要的是」「与此同时」这类说明文连接词开段或堆设定。若要补充信息，优先让信息出现在动作、对白、物件变化或对手反应里；全章「除了/除此之外/此外」合计最多 1 次。",
        "**破折号**：用破折号拖尾补充、叠比喻或改述的句子全章最多 1 句；事实、体感、强调三连结构会显得灌水。能用句号、逗号、动作停顿解决时，优先用这些方式。",
        "**信息**：大约每 300～500 字至少出现一条可复述的新事实（人物立场、线索、因果、决策、关系变化之一），避免只换手改比喻形容同一件事。",
        "**情节密度（段落级）**：以空行分段为准，每一段内须至少含一项：具体动作并带轻微后果、有信息量的对白、发现/误会/决定之一落地、或可见的空间位移/关系试探；连续写景段也配合人物动作、对白或取舍。",
        "**对白厚度**：短促台词适合压迫、打断、反问或情绪爆点；关键交锋减少连续「嗯/谁/为什么/不知道」式问答。每个重要对话回合至少让一方说出态度、筹码、隐瞒、威胁、试探或新信息，并在 2-3 轮内穿插动作、沉默或环境反应。",
        "**视角**：POV 体感描写少而准即可；同一情绪用一个准确描写落点即可；设定交代优先对白、动作或一句平叙，减少长串内心排比。",
        "**扩写**：需要加长时，加有信息的对话轮次、可见动作链、带后果的选择；减少复制粘贴式「众人震惊」排比，或重复描写同一条「电流/暖流/针刺」体感。",
        # ── 新增：体感比喻灌水（最常见的隐性八股）──
        "**体感比喻（控密度）**：同一段里「像电流」「像烈火」「像针刺」「暖流涌过」「寒意蔓延」等体感比喻最多出现 1 次；描写同一人物同一情绪的体感句，全段控制在 2 句以内；多余的用具体行为（手抖、嘴角微扯、脚步顿住）替换。",
        "**重复震撼/感叹（控密度）**：「不敢置信」「难以置信」「心跳骤停」「脑袋一片空白」等高惊觉词汇，每章最多各出现 1 次；旁观者震惊反应写 1 条有名有姓的即可，减少「众人皆惊」「所有人都」「全场哗然」等无名群体句连续出现。",
        "**开场/过渡八股（控模板）**：段落开头少用「就在此时」「与此同时」「话音刚落」「就在这时」「然而」单独成句充当转场；「这一刻，他明白了……」「那一瞬间……」这类情绪升华收尾全章最多用 1 次。",
        "**内心独白膨胀（控排比）**：人物内心独白（含括号标注的心理活动）若超过 3 行，在其中插入至少 1 个外部动作或对白节点打断；「他想，……他想，……他又想……」结构连续堆叠会拖慢节奏。",
    ]
    if beat_mode and beat_target_words is not None and beat_target_words <= 900:
        lines.extend(
            [
                "",
                "**节拍**：本段目标字数偏紧，优先完成大纲里的动作与关键对白；纠正式排比与内心铺陈从简。",
            ]
        )
    return "\n".join(lines)
